/**
 * 從縣市名推算管轄法院名稱，找不到回 'default'
 */
export function lookupCourt(city: string): string {
  if (!city) return 'default'
  const normalized = city.trim()
  return regionCourtMap[normalized] ?? regionCourtMap[normalized.replace(/台/g, '臺')] ?? 'default'
}
